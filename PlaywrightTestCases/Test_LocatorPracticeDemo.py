from playwright.sync_api import Page, expect
def test_locators(page: Page):
    page.goto("https://testautomationpractice.blogspot.com/p/playwrightpractice.html")
    #get_by_alt_text()
    expect(page.get_by_alt_text("logo image")).to_be_visible()
    #get_by_text()
    expect(page.get_by_text("Locate elements by their text content.")).to_have_text("Locate elements by their text content.")
    expect(page.get_by_text("Another paragraph with")).to_be_visible()
    #get_by_label()
    page.get_by_label("Email Address:").fill("abc@gmail.com")
    page.get_by_label("Password:").fill("12345678")
    page.get_by_label("Your Age:").fill("25")
    page.get_by_label(" Standard").click()
    page.wait_for_timeout(2000)
    #get_by_placeholder()
    page.get_by_placeholder("Enter your full name").fill("John")
    page.get_by_placeholder("Phone number (xxx-xxx-xxxx)").fill("123456789")
    page.get_by_placeholder("Type your message here...").fill("I a practicing playwright")
    page.get_by_placeholder("Search products...").fill("Good knowlegde")
    #get_by_role()
    expect(page.get_by_role("button", name="Primary Action")).to_be_visible()
    expect(page.get_by_role("button", name="Toggle Button")).to_be_visible()
    page.get_by_label("Username:").fill("Reena")
    page.get_by_role("checkbox",name="Accept terms").click()
    #get_by_tittle()
    expect(page.get_by_title("Home page link")).to_have_text("Home")
    expect(page.get_by_title("Click to save your changes")).to_have_text("Save")
    #get_by_testid()
    expect(page.get_by_test_id("profile-name")).to_have_text("John Doe")
    expect(page.get_by_test_id("profile-email")).to_have_text("john.doe@example.com")